    function normalizeLang(lang) {
        if (!lang) return "en";
        const code = String(lang).toLowerCase().trim().replace(/_/g, "-");
        const base = code.split("-")[0];
        return Object.hasOwn(STRINGS, base) ? base : "en";
    }

    let currentLang = "en";

    function setLang(lang) {
        currentLang = normalizeLang(lang);
        return currentLang;
    }

    function getLang() {
        return currentLang;
    }

    function t(key, lang, params = null) {
        let targetLang = lang;
        let targetParams = params;
        if (lang && typeof lang === "object") {
            targetParams = lang;
            targetLang = currentLang;
        } else if (!targetLang) {
            targetLang = currentLang;
        }

        const primary = normalizeLang(targetLang);
        const dict = STRINGS[primary] || STRINGS.en;
        let text = dict[key] !== undefined ? dict[key] : (STRINGS.en[key] !== undefined ? STRINGS.en[key] : key);
        if (targetParams && typeof targetParams === "object") {
            for (const [paramKey, value] of Object.entries(targetParams)) {
                text = text.replaceAll(`{${paramKey}}`, String(value));
            }
        }
        return text;
    }

    function applyToDOM(root = document, lang = null) {
        if (!root) return;
        const normalized = lang ? setLang(lang) : currentLang;

        // Text content
        const elements = root.querySelectorAll("[data-i18n]");
        for (const el of elements) {
            const key = el.getAttribute("data-i18n");
            if (key) {
                el.textContent = t(key, normalized);
            }
        }

        // Title attributes
        const titles = root.querySelectorAll("[data-i18n-title]");
        for (const el of titles) {
            const key = el.getAttribute("data-i18n-title");
            if (key) {
                el.setAttribute("title", t(key, normalized));
            }
        }

        // Placeholder attributes
        const placeholders = root.querySelectorAll("[data-i18n-placeholder]");
        for (const el of placeholders) {
            const key = el.getAttribute("data-i18n-placeholder");
            if (key) {
                el.setAttribute("placeholder", t(key, normalized));
            }
        }

        // Aria-label attributes
        const arias = root.querySelectorAll("[data-i18n-aria]");
        for (const el of arias) {
            const key = el.getAttribute("data-i18n-aria");
            if (key) {
                el.setAttribute("aria-label", t(key, normalized));
            }
        }

        // Templates (pre-translate unmounted template contents)
        const templates = root.querySelectorAll("template");
        for (const tpl of templates) {
            if (tpl.content) {
                applyToDOM(tpl.content, normalized);
            }
        }
    }

    
